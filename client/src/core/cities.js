export const cityById = (id) => CITIES.find((x) => x.id === id) || CITIES[0]
/** Israel keeps one day of Yom Tov, the diaspora two. */
export const inIsrael = (city) => city.zone === 'Asia/Jerusalem'
export const cityName = (city, lang) => (lang === 'he' ? city.he : city.en)

const clean = (x) => x.toLowerCase().replace(/[֑-ׇ'’׳״"\-\s.]/g, '')
/** Cities whose Hebrew or English name contains the query (ignores case, spaces, punctuation, niqqud). */
export function searchCities(query) {
  const q = clean(query)
  if (!q) return CITIES
  return CITIES.filter((x) => clean(x.he).includes(q) || clean(x.en).includes(q))
}
